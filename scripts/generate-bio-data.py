"""
Regenerates EDSSI's exobiology spawn data from checkouts of Silarn's EDMC plugins:

    git clone https://github.com/Silarn/EDMC-BioScan
    git clone https://github.com/Silarn/EDMC-ExploData
    python scripts/generate-bio-data.py <EDMC-BioScan> <EDMC-ExploData>

BioScan holds the species rules (worked out by the community from Canonn's data), the region
groups and the nebula positions; ExploData the colour variants, colony distances and
klightspeed's galactic region map. The files only hold data, so they are loaded straight from the
checkouts rather than imported as packages. Writes three `*.generated.ts` files next to
`src/main/history/biology/predict.ts`; run oxfmt on them afterwards.
"""

import importlib.util
import json
import pathlib
import subprocess
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'main' / 'history' / 'biology'

RULE_KEYS = {
    'atmosphere': 'atmosphere',
    'atmosphere_component': 'atmosphereComponent',
    'min_gravity': 'minGravity',
    'max_gravity': 'maxGravity',
    'min_temperature': 'minTemperature',
    'max_temperature': 'maxTemperature',
    'min_pressure': 'minPressure',
    'max_pressure': 'maxPressure',
    'max_orbital_period': 'maxOrbitalPeriod',
    'volcanism': 'volcanism',
    'body_type': 'bodyType',
    'regions': 'regions',
    'star': 'star',
    'parent_star': 'parentStar',
    'nebula': 'nebula',
    'guardian': 'guardian',
    'tuber': 'tuber',
    'bodies': 'bodies',
    'distance': 'distance',
    'system': 'system',
}
# BioScan's evaluator never reads these, so neither does EDSSI (brain trees carry a `region` that
# would otherwise shut them out of most of the galaxy).
IGNORED_KEYS = {'region', 'main_star'}


def load(path: pathlib.Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def commit(repo: pathlib.Path) -> str:
    return subprocess.run(['git', '-C', str(repo), 'rev-parse', 'HEAD'], capture_output=True,
                          text=True, check=True).stdout.strip()


def convert_rule(rule: dict) -> dict:
    out = {}
    for key, value in rule.items():
        if key in IGNORED_KEYS:
            continue
        if key not in RULE_KEYS:
            raise ValueError(f'Unknown rule key {key!r}; teach predict.ts and this script about it')
        if key == 'star':
            stars = value if isinstance(value, list) else [value]
            value = [list(star) if isinstance(star, (list, tuple)) else star for star in stars]
        out[RULE_KEYS[key]] = value
    return out


def main() -> None:
    bioscan = pathlib.Path(sys.argv[1]).resolve()
    explodata = pathlib.Path(sys.argv[2]).resolve()
    bio_data = bioscan / 'src' / 'bio_scan' / 'bio_data'
    nebula_data = bioscan / 'src' / 'bio_scan' / 'nebula_data'
    explo = explodata / 'src' / 'ExploData' / 'explo_data'

    catalog: dict = {}
    for ruleset in sorted((bio_data / 'rulesets').glob('*.py')):
        catalog |= load(ruleset, ruleset.stem).catalog
    # species.py adds a few genera inline, after importing the rulesets as a package.
    source = (bio_data / 'species.py').read_text(encoding='utf-8')
    inline = source[source.index('_mound_amphora'):source.index('rules: dict')]
    scope: dict = {}
    exec('from typing import Mapping\n' + inline, scope)
    catalog |= scope['_mound_amphora']

    genus_info = load(explo / 'bio_data' / 'genus.py', 'genus').data
    genera = []
    for genus_code, species in catalog.items():
        info = genus_info.get(genus_code)
        if info is None:
            continue  # A species filed under its own code with no rules (Stratum Aranaemus).
        colours = info.get('colors', {})
        genera.append({
            'code': genus_code,
            'name': info['name'],
            'colonyDistance': info['distance'],
            'multiple': info['multiple'],
            **({'starColours': colours['star']} if 'star' in colours else {}),
            'species': [
                {
                    'code': code,
                    'name': data['name'],
                    'value': data['value'],
                    **({'starColours': colours['species'][code]['star']}
                       if code in colours.get('species', {}) and 'star' in colours['species'][code]
                       else {}),
                    **({'elementColours': colours['species'][code]['element']}
                       if code in colours.get('species', {}) and 'element' in colours['species'][code]
                       else {}),
                    'rules': [convert_rule(rule) for rule in data['rulesets']],
                }
                for code, data in species.items()
            ],
        })

    header = (
        '// Generated by scripts/generate-bio-data.py from Silarn/EDMC-BioScan@{bioscan} and\n'
        '// Silarn/EDMC-ExploData@{explodata}. Do not edit by hand.\n'
    ).format(bioscan=commit(bioscan), explodata=commit(explodata))

    def dump(value) -> str:
        return json.dumps(value, ensure_ascii=False)

    (OUT / 'species.generated.ts').write_text(
        header + "\nimport type { GenusRules } from './rules';\n\n"
        '/** Every genus with its species, the conditions each can spawn under, and its colours. */\n'
        f'export const GENERA: readonly GenusRules[] = {dump(genera)};\n',
        encoding='utf-8', newline='\n')

    regions = load(bio_data / 'regions.py', 'regions')
    region_map = load(explo / 'RegionMapData.py', 'region_map')
    (OUT / 'regions.generated.ts').write_text(
        header +
        '\n/** Galactic region names by id; id 0 is outside the map. */\n'
        f'export const REGION_NAMES: readonly (string | null)[] = {dump(region_map.regions)};\n\n'
        '/**\n * The region map, a row per z step of 4096/83 ly from z = -24105, each a run-length list of\n'
        ' * (length, region id) pairs flattened, x steps from x = -49985.\n */\n'
        'export const REGION_ROWS: readonly (readonly number[])[] = '
        f'{dump([[n for pair in row for n in pair] for row in region_map.regionmap])};\n\n'
        '/** Named groups of region ids that the species rules refer to. */\n'
        'export const REGION_GROUPS: Readonly<Record<string, readonly number[]>> = '
        f'{dump(regions.region_map)};\n\n'
        '/** Guardian zones: radius in ly and centre. */\n'
        'export const GUARDIAN_ZONES: readonly { name: string; radius: number; centre: readonly [number, number, number] }[] = '
        f'{dump([{"name": k, "radius": r, "centre": c} for k, (r, c) in regions.guardian_nebulae.items()])};\n\n'
        '/** Where Sinuous Tubers grow: a band of distances in ly from a centre. */\n'
        'export const TUBER_ZONES: readonly { name: string; min: number; max: number; centre: readonly [number, number, number] }[] = '
        f'{dump([{"name": k, "min": d[0], "max": d[1], "centre": c} for k, (d, c) in regions.tuber_zones.items()])};\n',
        encoding='utf-8', newline='\n')

    stars = load(nebula_data / 'reference_stars.py', 'reference_stars')
    sectors = load(nebula_data / 'sectors.py', 'sectors')
    flat = lambda coords: [round(n, 5) for xyz in coords.values() for n in xyz]
    (OUT / 'nebulae.generated.ts').write_text(
        header +
        '\n/** Sector names that are nebulae themselves: a system named in one is in a nebula. */\n'
        f'export const NEBULA_SECTORS: readonly string[] = {dump(sectors.data)};\n\n'
        '/** Reference systems inside large nebulae, as flattened x, y, z triples. */\n'
        'export const LARGE_NEBULAE: readonly number[] = '
        f'{dump(flat(stars.coordinates | stars.named_coordinates))};\n\n'
        '/** Planetary nebulae, as flattened x, y, z triples. */\n'
        f'export const PLANETARY_NEBULAE: readonly number[] = {dump(flat(stars.planetary_coordinates))};\n',
        encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
